/**
 * Normalization & Lookup Helper Functions
 */

export function normalizeKey(key) {
  if (!key) return "";
  return String(key).trim().toLowerCase();
}

export function getCategoryLabel(category, lang = "en") {
  if (!category) return "";
  if (category === "All" || normalizeKey(category) === "all") {
    return SYSTEM_TERMS.allCategories[lang] || SYSTEM_TERMS.allCategories.en;
  }
  // Search exact or case-insensitive
  for (const [catKey, translations] of Object.entries(CATEGORY_VOCABULARY)) {
    if (normalizeKey(catKey) === normalizeKey(category)) {
      return translations[lang] || translations.en || catKey;
    }
  }
  return category;
}

export function getUnitLabel(unit, lang = "en") {
  if (!unit) return "";
  const norm = normalizeKey(unit);
  for (const [uKey, translations] of Object.entries(UNIT_VOCABULARY)) {
    if (norm === uKey || norm === normalizeKey(translations.en)) {
      return translations[lang] || translations.en || unit;
    }
  }
  return unit;
}

export function getGradeLabel(grade, lang = "en") {
  if (!grade) return "";
  const norm = String(grade).toUpperCase().trim();
  if (GRADE_VOCABULARY[norm]) {
    return GRADE_VOCABULARY[norm][lang] || GRADE_VOCABULARY[norm].en || `Grade ${grade}`;
  }
  return `Grade ${grade}`;
}

export function getOrderStatusLabel(status, lang = "en") {
  if (!status) return "";
  for (const [stKey, translations] of Object.entries(ORDER_STATUS_VOCABULARY)) {
    if (normalizeKey(stKey) === normalizeKey(status)) {
      return translations[lang] || translations.en || status;
    }
  }
  return status;
}

export function getSystemTerm(termKey, lang = "en") {
  if (SYSTEM_TERMS[termKey]) {
    return SYSTEM_TERMS[termKey][lang] || SYSTEM_TERMS[termKey].en || termKey;
  }
  return termKey;
}
