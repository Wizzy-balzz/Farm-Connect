function normalize(str) {
  return str ? String(str).trim().toLowerCase() : "";
}

export function translateCategory(cat, lang = "en") {
  if (!cat) return "";
  for (const [k, v] of Object.entries(CATEGORY_VOCABULARY)) {
    if (normalize(k) === normalize(cat)) return v[lang] || v.en || cat;
  }
  return cat;
}

export function translateUnit(unit, lang = "en") {
  if (!unit) return "";
  for (const [k, v] of Object.entries(UNIT_VOCABULARY)) {
    if (normalize(k) === normalize(unit)) return v[lang] || v.en || unit;
  }
  return unit;
}

export function translateGrade(grade, lang = "en") {
  if (!grade) return "";
  const norm = String(grade).toUpperCase().trim();
  if (GRADE_VOCABULARY[norm]) {
    return GRADE_VOCABULARY[norm][lang] || GRADE_VOCABULARY[norm].en || `Grade ${grade}`;
  }
  return `Grade ${grade}`;
}

export function translateOrderStatus(status, lang = "en") {
  if (!status) return "";
  for (const [k, v] of Object.entries(ORDER_STATUS_VOCABULARY)) {
    if (normalize(k) === normalize(status)) return v[lang] || v.en || status;
  }
  return status;
}
